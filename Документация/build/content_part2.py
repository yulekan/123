        'а таблицы обновляются автоматически;',
        'предотвращение ошибок: значения проверяются до сохранения, а подсказка о норме и '
        'остатке показывается до нажатия кнопки;',
        'единообразие: все разделы построены по схеме «заголовок — панель действий — таблица», '
        'все диалоги — по схеме «поля — кнопки»;',
        'единый доступ: вход в систему не требуется, все разделы доступны сразу после '
